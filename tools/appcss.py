def toml(p):
    d = {}
    for l in open(p):
        m = re.match(r'^\s*([A-Za-z0-9_-]+)\s*=\s*"([^"]*)"', l)
        if m: d[m.group(1)] = m.group(2)
    return d
def rgb(h): return ",".join(str(int(h[i:i+2], 16)) for i in (1, 3, 5))

