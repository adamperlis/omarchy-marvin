def colmap(c):
    """Omarchy's colorN + role names, resolved to Marvin hex. The ANSI order is
    background, red, green, yellow, blue, magenta, cyan, foreground, muted."""
    return dict(
        background=c["background"], foreground=c["foreground"], accent=c["accent"],
        cursor=c.get("bright_foreground", c["foreground"]),
        selection_background=c["selection"], selection_foreground=c.get("bright_foreground", c["foreground"]),
        color0=c["background"], color1=c["red"], color2=c["green"], color3=c["yellow"],
        color4=c["blue"], color5=c["magenta"], color6=c["cyan"], color7=c["foreground"], color8=c["muted"],
    )

